-- =====================================================
-- 01_tables.sql - Creación de tablas
-- Sistema de gestión para taller de motos
-- =====================================================

-- 1. Tipos de usuario: ADMINISTRADOR, VENDEDOR, TRABAJADOR
CREATE TABLE roles (
    id_rol         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre         VARCHAR2(30)  NOT NULL,
    descripcion    VARCHAR2(150)
);

-- 2. Personas que pueden entrar al sistema
CREATE TABLE usuarios (
    id_usuario     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre         VARCHAR2(100) NOT NULL,
    usuario        VARCHAR2(30)  NOT NULL,
    contrasena     VARCHAR2(200) NOT NULL,
    id_rol         NUMBER        NOT NULL,
    activo         CHAR(1)       DEFAULT 'S' NOT NULL,
    fecha_creacion DATE          DEFAULT SYSDATE NOT NULL
);

-- 3. Tipo de producto: frenos, motor, aceites...
CREATE TABLE categorias (
    id_categoria   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre         VARCHAR2(50)  NOT NULL,
    descripcion    VARCHAR2(150)
);

-- 4. Fabricante del producto: Yamaha, Mobil...
CREATE TABLE marcas (
    id_marca       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre         VARCHAR2(50)  NOT NULL
);

-- 5. Personas que traen su moto o compran repuestos
CREATE TABLE clientes (
    id_cliente     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    documento      VARCHAR2(20)  NOT NULL,
    nombre         VARCHAR2(100) NOT NULL,
    telefono       VARCHAR2(20)  NOT NULL,
    correo         VARCHAR2(100),
    fecha_registro DATE          DEFAULT SYSDATE NOT NULL
);

-- 6. Motos de cada cliente (un cliente puede tener varias)
CREATE TABLE motos_cliente (
    id_moto        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    placa          VARCHAR2(10)  NOT NULL,
    marca          VARCHAR2(40)  NOT NULL,
    modelo         VARCHAR2(60)  NOT NULL,
    anio           NUMBER(4),
    apodo          VARCHAR2(40),
    id_cliente     NUMBER        NOT NULL
);

-- 7. Inventario de repuestos
CREATE TABLE repuestos (
    id_repuesto    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    referencia     VARCHAR2(30)  NOT NULL,
    nombre         VARCHAR2(100) NOT NULL,
    id_categoria   NUMBER        NOT NULL,
    id_marca       NUMBER        NOT NULL,
    precio         NUMBER(12,2)  NOT NULL,
    stock          NUMBER(6)     DEFAULT 0 NOT NULL,
    stock_minimo   NUMBER(6)     DEFAULT 5 NOT NULL
);

-- 8. Arreglos que se le hacen a cada moto
CREATE TABLE trabajos (
    id_trabajo     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_moto        NUMBER        NOT NULL,
    id_usuario     NUMBER        NOT NULL,
    descripcion    VARCHAR2(300) NOT NULL,
    fecha          DATE          DEFAULT SYSDATE NOT NULL,
    costo          NUMBER(12,2)  DEFAULT 0 NOT NULL,
    estado         VARCHAR2(15)  DEFAULT 'PENDIENTE' NOT NULL
    fecha_terminado DATE
);

CREATE TABLE ventas (
    id_venta    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    fecha       DATE   DEFAULT SYSDATE NOT NULL,
    id_cliente  NUMBER,
    id_moto     NUMBER,
    id_trabajo  NUMBER,
    id_usuario  NUMBER NOT NULL
);

-- 9. Ventas y compras de repuestos
CREATE TABLE movimientos (
    id_movimiento   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    tipo            VARCHAR2(10)  NOT NULL,
    id_repuesto     NUMBER        NOT NULL,
    cantidad        NUMBER(6)     NOT NULL,
    precio_unitario NUMBER(12,2)  NOT NULL,
    fecha           DATE          DEFAULT SYSDATE NOT NULL,
    id_usuario      NUMBER        NOT NULL,
    id_cliente      NUMBER,
    id_trabajo      NUMBER
    id_trabajo      NUMBER,
    id_venta        NUMBER
);
);