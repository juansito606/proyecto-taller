-- 05_actualizacion_ventas.sql - Actualización: tabla VENTAS
-- Una venta agrupa en un solo registro: cliente, moto, mano de obra (trabajo) y repuestos.
-- Se ejecuta UNA vez sobre una base que ya tiene 01, 02 y 03.
-- =====================================================

CREATE TABLE ventas (
    id_venta    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    fecha       DATE   DEFAULT SYSDATE NOT NULL,
    id_cliente  NUMBER,
    id_moto     NUMBER,
    id_trabajo  NUMBER,
    id_usuario  NUMBER NOT NULL
);

ALTER TABLE movimientos ADD id_venta NUMBER;

ALTER TABLE ventas ADD CONSTRAINT pk_ventas PRIMARY KEY (id_venta);
ALTER TABLE ventas ADD CONSTRAINT uq_ventas_trabajo UNIQUE (id_trabajo);
ALTER TABLE ventas ADD CONSTRAINT fk_ventas_cliente FOREIGN KEY (id_cliente) REFERENCES clientes (id_cliente);
ALTER TABLE ventas ADD CONSTRAINT fk_ventas_moto FOREIGN KEY (id_moto) REFERENCES motos_cliente (id_moto);
ALTER TABLE ventas ADD CONSTRAINT fk_ventas_trabajo FOREIGN KEY (id_trabajo) REFERENCES trabajos (id_trabajo);
ALTER TABLE ventas ADD CONSTRAINT fk_ventas_usuario FOREIGN KEY (id_usuario) REFERENCES usuarios (id_usuario);
ALTER TABLE movimientos ADD CONSTRAINT fk_mov_venta FOREIGN KEY (id_venta) REFERENCES ventas (id_venta);

-- Pasar los datos que ya existen al nuevo formato
DECLARE
  v_vendedor NUMBER;
  v_id       NUMBER;
BEGIN
  SELECT NVL(MIN(CASE WHEN r.nombre = 'VENDEDOR' THEN u.id_usuario END), MIN(u.id_usuario))
    INTO v_vendedor
    FROM usuarios u JOIN roles r ON r.id_rol = u.id_rol;

  -- 1. Una venta por cada trabajo (su mano de obra + los repuestos que se le vendieron)
  FOR reg IN (SELECT tr.id_trabajo, tr.fecha, tr.id_moto, mc.id_cliente
                FROM trabajos tr JOIN motos_cliente mc ON mc.id_moto = tr.id_moto
               WHERE NOT EXISTS (SELECT 1 FROM ventas v WHERE v.id_trabajo = tr.id_trabajo)) LOOP
    INSERT INTO ventas (fecha, id_cliente, id_moto, id_trabajo, id_usuario)
    VALUES (reg.fecha, reg.id_cliente, reg.id_moto, reg.id_trabajo, v_vendedor)
    RETURNING id_venta INTO v_id;
    UPDATE movimientos SET id_venta = v_id
     WHERE id_trabajo = reg.id_trabajo AND tipo = 'VENTA' AND id_venta IS NULL;
  END LOOP;

  -- 2. Las ventas de mostrador (sin trabajo)
  FOR reg IN (SELECT id_movimiento, fecha, id_cliente, id_usuario
                FROM movimientos WHERE tipo = 'VENTA' AND id_venta IS NULL) LOOP
    INSERT INTO ventas (fecha, id_cliente, id_usuario)
    VALUES (reg.fecha, reg.id_cliente, reg.id_usuario)
    RETURNING id_venta INTO v_id;
    UPDATE movimientos SET id_venta = v_id WHERE id_movimiento = reg.id_movimiento;
  END LOOP;
END;
/

COMMIT;


