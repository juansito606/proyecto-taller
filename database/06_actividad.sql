CREATE TABLE actividad (
    id_actividad NUMBER GENERATED BY DEFAULT AS IDENTITY,
    fecha        DATE DEFAULT SYSDATE NOT NULL,
    id_usuario   NUMBER NOT NULL,
    tipo         VARCHAR2(20) NOT NULL,
    accion       VARCHAR2(200 CHAR) NOT NULL,
    detalle      VARCHAR2(1000 CHAR),
    monto        NUMBER(12,2)
);

ALTER TABLE actividad ADD CONSTRAINT pk_actividad PRIMARY KEY (id_actividad);
ALTER TABLE actividad ADD CONSTRAINT fk_actividad_usuario FOREIGN KEY (id_usuario) REFERENCES usuarios (id_usuario) ON DELETE CASCADE;
ALTER TABLE actividad ADD CONSTRAINT ck_actividad_tipo CHECK (tipo IN ('ORDEN','ASIGNACION','AVANCE','TERMINADO','EDICION','ELIMINACION','VENTA','ANULACION','COMPRA','INVENTARIO'));

COMMIT;

