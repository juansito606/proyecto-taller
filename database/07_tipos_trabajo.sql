-- A los trabajos que ya existen se les pone su tipo segun lo que dice la descripcion
UPDATE trabajos t SET id_tipo = (
  SELECT tt.id_tipo FROM tipos_trabajo tt WHERE tt.nombre = CASE
    WHEN UPPER(t.descripcion) LIKE '%ACEITE%' THEN 'Cambio de aceite'
    WHEN UPPER(t.descripcion) LIKE '%FRENO%' OR UPPER(t.descripcion) LIKE '%PASTILLA%' OR UPPER(t.descripcion) LIKE '%BANDA%' THEN 'Frenos'
    WHEN UPPER(t.descripcion) LIKE '%ARRASTRE%' OR UPPER(t.descripcion) LIKE '%CADENA%' THEN 'Transmision'
    WHEN UPPER(t.descripcion) LIKE '%ELECTRIC%' OR UPPER(t.descripcion) LIKE '%BATERIA%' OR UPPER(t.descripcion) LIKE '%BOMBILLO%' THEN 'Sistema electrico'
    WHEN UPPER(t.descripcion) LIKE '%LLANTA%' THEN 'Llantas'
    WHEN UPPER(t.descripcion) LIKE '%MANTENIMIENTO%' THEN 'Mantenimiento general'
    WHEN UPPER(t.descripcion) LIKE '%MOTOR%' OR UPPER(t.descripcion) LIKE '%BUJIA%' OR UPPER(t.descripcion) LIKE '%SINCRONIZ%' THEN 'Motor'
    ELSE 'Otro' END)
WHERE t.id_tipo IS NULL;

COMMIT;
