CREATE TABLE tipos_trabajo (
    id_tipo         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre          VARCHAR2(60 CHAR) NOT NULL,
    descripcion     VARCHAR2(200 CHAR),
    precio_sugerido NUMBER(12,2) DEFAULT 0 NOT NULL
);

ALTER TABLE tipos_trabajo ADD CONSTRAINT pk_tipos_trabajo PRIMARY KEY (id_tipo);
ALTER TABLE tipos_trabajo ADD CONSTRAINT uq_tipos_trabajo_nombre UNIQUE (nombre);
ALTER TABLE tipos_trabajo ADD CONSTRAINT ck_tipos_trabajo_precio CHECK (precio_sugerido >= 0);

ALTER TABLE trabajos ADD id_tipo NUMBER;
ALTER TABLE trabajos ADD CONSTRAINT fk_trabajos_tipo FOREIGN KEY (id_tipo) REFERENCES tipos_trabajo (id_tipo);

